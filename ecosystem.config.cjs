/**
 * Запуск магазина под PM2.
 *
 * PM2, а не systemd — потому что сервер, на котором сайт живёт, целиком
 * управляется через PM2: там же работают ещё шесть приложений. Один способ
 * запуска на всю машину стоит дороже, чем аккуратная песочница systemd:
 * иначе через полгода никто не вспомнит, где искать магазин.
 *
 *   pm2 start ecosystem.config.cjs
 *   pm2 save            # чтобы поднялся после перезагрузки
 *   pm2 logs vdf
 *
 * Расширение .cjs обязательно: в package.json нет "type": "module", но PM2
 * читает конфиг как CommonJS, а Node в свежих версиях уже спорит с .js без
 * явного указания формата.
 */
module.exports = {
  apps: [
    {
      name: "vdf",
      cwd: "/var/www/vdf.by",

      // Вызываем next напрямую, а не через `npm start`: иначе между PM2 и
      // сервером висит лишний процесс npm, и сигнал остановки доходит до
      // Node через посредника.
      script: "node_modules/next/dist/bin/next",

      // Порт не 3000. На боевом сервере 3000 занят главным сайтом
      // prime-auto, 3010 — тоже занят. 3011 свободен.
      args: "start --port 3011",

      // Путь к Node указан явно, и это не перестраховка.
      //
      // Системный Node на сервере — v18, на нём работают чужие приложения,
      // и обновлять его нельзя. А better-sqlite3 требует Node 22 и выше:
      // без этой строки PM2 запустил бы магазин на своём интерпретаторе, и
      // он упал бы на первом же обращении к базе.
      //
      // Версия зашита цифрами намеренно. Пути вида ~/.nvm/current PM2
      // разворачивает один раз при старте, и после `nvm install` магазин
      // молча переехал бы на другой Node.
      interpreter: "/root/.nvm/versions/node/v22.23.2/bin/node",

      env: { NODE_ENV: "production" },

      instances: 1,
      exec_mode: "fork",

      // Утечки не ожидаем, но если она случится, перезапуск дешевле, чем
      // OOM-killer, выбирающий жертву среди чужих приложений.
      max_memory_restart: "700M",
      autorestart: true,

      // Токены в конфиге не нужны: .env приложение читает само при старте.
      // Заодно они не попадают в `pm2 describe`, который смотрят все.
    },
  ],
};
