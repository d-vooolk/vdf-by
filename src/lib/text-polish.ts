import { AiError, cleanPlainText, completeTraced } from "./ai";

export const MAX_POLISH_TEXT = 10000;

const POLISH_PROMPT = `Ты — корректор внутренней базы знаний автосервиса: мастера описывают, как ремонтировать фары, ставить би-LED модули, разбирать и собирать конкретные машины.

Исправь текст мастера:
- орфографию, опечатки и знаки препинания;
- если фраза читается тяжело или двусмысленно, перестрой её коротко и просто.

Не делай литературный рерайт. Текст должен остаться деловым, чётким и простым, своими словами мастера.
- Сохрани весь смысл, все факты, цифры, размеры, артикулы, названия деталей, марок и моделей. Ничего не добавляй и не выдумывай, ничего не убирай.
- Профессиональный сленг мастеров (линза, бленда, маска, герметик, корректор) оставляй как есть, если он понятен.
- Сохрани порядок мыслей, абзацы, переносы строк, нумерацию и списки.
- Без Markdown, без звёздочек и заголовков, без эмодзи.
- Если исправлять нечего, верни текст без изменений.

Верни только исправленный текст, без пояснений и вступлений.`;

export async function polishText(text: string): Promise<string> {
  const { text: result } = await completeTraced(POLISH_PROMPT, text, "crm-polish", { temperature: 0.2 });
  const polished = cleanPlainText(result);
  if (!polished) throw new AiError("Нейросеть вернула пустой ответ — попробуйте ещё раз");
  return polished;
}
